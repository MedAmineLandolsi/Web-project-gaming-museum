function projetweb_supported_languages(): array {
    // code => label (displayed in UI)
    return [
        'fr' => 'FR',
        'en' => 'EN',
        'ar' => 'العربية',
        'zh' => '中文',
        'es' => 'ES',
        'de' => 'DE',
        'it' => 'IT',
        'pt' => 'PT',
        'tr' => 'TR',
    ];
}

function projetweb_get_lang(): string {
    $lang = strtolower((string) ($_SESSION['lang'] ?? 'fr'));
    $supported = array_keys(projetweb_supported_languages());
    return in_array($lang, $supported, true) ? $lang : 'fr';
}

function projetweb_set_lang(string $lang): void {
    $lang = strtolower(trim($lang));
    $supported = array_keys(projetweb_supported_languages());
    if (!in_array($lang, $supported, true)) {
        return;
    }
    $_SESSION['lang'] = $lang;
}

function projetweb_get_dir(?string $lang = null): string {
    $lang = $lang ? strtolower(trim($lang)) : projetweb_get_lang();
    return in_array($lang, ['ar'], true) ? 'rtl' : 'ltr';
}

